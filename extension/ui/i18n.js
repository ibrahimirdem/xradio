// XRadio arayüz çevirileri. Anahtar Türkçe metnin kendisidir (gettext tarzı): Türkçe arayüzde anahtar
// olduğu gibi görünür, diğer tüm dillerde İngilizce karşılığı kullanılır. DJ'lerin yayın dili ayrıdır
// (Gemini 15 dili konuşabilir); arayüz yalnızca Türkçe ve İngilizce'dir.
import { uiLangOf } from '../lib/config.js';

let LANG = 'tr';

export function setUiLang(code) {
  LANG = uiLangOf(code);
  if (typeof document !== 'undefined') document.documentElement.lang = LANG;
  return LANG;
}
export function getUiLang() { return LANG; }
export function uiLocale() { return LANG === 'tr' ? 'tr-TR' : 'en-US'; }

export function t(key, vars) {
  const s = LANG === 'en' ? (EN[key] ?? key) : key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
}

// data-i18n (metin), data-i18n-title (title) ve data-i18n-ph (placeholder) işaretli öğeleri çevirir.
// Asıl Türkçe metin data-* içine yazılır; böylece tekrar çağrılırsa yine doğru anahtardan çevrilir.
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.dataset.i18n || (el.dataset.i18n = el.textContent.trim());
    el.textContent = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle || (el.dataset.i18nTitle = el.getAttribute('title') || '');
    if (key) el.title = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-ph]')) {
    const key = el.dataset.i18nPh || (el.dataset.i18nPh = el.getAttribute('placeholder') || '');
    if (key) el.placeholder = t(key);
  }
}

